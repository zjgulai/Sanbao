#!/usr/bin/env node
import { lstatSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const repoRoot = fileURLToPath(new URL('../../', import.meta.url))
const defaultAssetsRoot = join(repoRoot, 'assets/experts')
const defaultProjection = join(repoRoot, 'apps/sage-shell/src/product/app/desktop/expert-registry.generated.ts')
const expectedIds = [
  ...Array.from({ length: 3 }, (_, i) => `MGT-${String(i + 1).padStart(3, '0')}`),
  ...Array.from({ length: 50 }, (_, i) => `AGT-${String(i + 1).padStart(3, '0')}`),
]

function requireRecord(value, label) {
  if (value === null || typeof value !== 'object' || Array.isArray(value)) throw new Error(`Invalid ${label}`)
  return value
}

function requireText(value, label) {
  if (typeof value !== 'string' || value.trim() === '' || value.length > 2000) throw new Error(`Invalid ${label}`)
  return value
}

function readAsset(root, path, maximumBytes) {
  // Every segment is checked: a trusted leaf name does not make a symlinked parent safe.
  let current = root
  for (const part of path.split('/')) {
    current = join(current, part)
    if (lstatSync(current).isSymbolicLink()) throw new Error(`Symlink in expert asset: ${path}`)
  }
  const stat = lstatSync(current)
  if (!stat.isFile() || stat.size === 0 || stat.size > maximumBytes) throw new Error(`Invalid expert asset: ${path}`)
  return readFileSync(current)
}

function avatarFiles(root) {
  const files = []
  function visit(directory) {
    const stat = lstatSync(directory)
    if (stat.isSymbolicLink() || !stat.isDirectory()) throw new Error('Invalid avatar directory')
    for (const entry of readdirSync(directory, { withFileTypes: true })) {
      const path = join(directory, entry.name)
      if (entry.isSymbolicLink()) throw new Error('Symlink in avatar directory')
      if (entry.isDirectory()) visit(path)
      else if (entry.isFile()) files.push(relative(root, path).split('\\').join('/'))
      else throw new Error('Invalid avatar entry')
    }
  }
  visit(root)
  return files.sort()
}

function rendererModule(registry) {
  const rows = registry.experts.map(expert => `    ${JSON.stringify(expert)},`).join('\n')
  return `// Generated by scripts/experts/renderer-assets.mjs --write. Do not edit.
// Catalogue content only; no runtime identities, grants or executable Presets.
export interface ExpertRecord {
  readonly id: string
  readonly roleKind: 'MGT' | 'AGT'
  readonly group: string | null
  readonly alias: string
  readonly title: string
  readonly mission: string
  readonly personality: string
  readonly avatar: string
  readonly designStatus: 'design_only'
}

export interface ExpertRegistry {
  readonly schemaVersion: 'sage.expert-registry.v1'
  readonly designStatus: 'design_only'
  readonly counts: { readonly managers: number; readonly agents: number; readonly total: number }
  readonly experts: readonly ExpertRecord[]
}

export const EXPERT_REGISTRY: ExpertRegistry = {
  schemaVersion: 'sage.expert-registry.v1',
  designStatus: 'design_only',
  counts: ${JSON.stringify(registry.counts)},
  experts: [
${rows}
  ],
}
`
}

export function loadExpertRendererAssets(assetsRoot = defaultAssetsRoot) {
  const rootStat = lstatSync(assetsRoot)
  if (!rootStat.isDirectory() || rootStat.isSymbolicLink()) throw new Error('Invalid expert assets root')
  const catalog = requireRecord(JSON.parse(readAsset(assetsRoot, 'expert-registry.json', 512 * 1024).toString('utf8')), 'expert catalogue')
  if (catalog.schemaVersion !== 'sage.expert-registry.v1' || catalog.designStatus !== 'design_only') {
    throw new Error('Expert catalogue must remain design_only')
  }
  const counts = requireRecord(catalog.counts, 'expert counts')
  if (counts.managers !== 3 || counts.agents !== 50 || counts.total !== 53 || !Array.isArray(catalog.experts) || catalog.experts.length !== 53) {
    throw new Error('Expert catalogue must contain 3 MGT and 50 AGT designs')
  }
  const seen = new Set()
  const avatarAssets = Object.create(null)
  const references = []
  const experts = catalog.experts.map(raw => {
    const expert = requireRecord(raw, 'expert')
    const id = requireText(expert.id, 'expert id')
    if (!expectedIds.includes(id) || seen.has(id)) throw new Error(`Invalid or duplicate expert id: ${id}`)
    seen.add(id)
    const roleKind = id.startsWith('MGT-') ? 'MGT' : 'AGT'
    if (expert.roleKind !== roleKind || expert.designStatus !== 'design_only' || expert.productionAuthorized !== false) {
      throw new Error(`Expert must remain a non-authorized design: ${id}`)
    }
    const avatar = `avatars/${id.toLowerCase()}/light/list-64.webp`
    if (expert.avatar !== avatar) throw new Error(`Invalid avatar path for ${id}`)
    const bytes = readAsset(assetsRoot, avatar, 128 * 1024)
    if (bytes.toString('ascii', 0, 4) !== 'RIFF' || bytes.toString('ascii', 8, 12) !== 'WEBP') {
      throw new Error(`Invalid WebP avatar for ${id}`)
    }
    const avatarUrl = `/assets/experts/${avatar}`
    avatarAssets[avatarUrl] = bytes.toString('base64')
    references.push(avatar.slice('avatars/'.length))
    return {
      id,
      roleKind,
      group: expert.group === null ? null : requireText(expert.group, `${id} group`),
      alias: requireText(expert.alias, `${id} alias`),
      title: requireText(expert.title, `${id} title`),
      mission: requireText(expert.mission, `${id} mission`),
      personality: requireText(expert.personality, `${id} personality`),
      avatar: avatarUrl,
      designStatus: 'design_only',
    }
  })
  if (JSON.stringify(avatarFiles(join(assetsRoot, 'avatars'))) !== JSON.stringify(references.sort())) {
    throw new Error('Expert avatar files differ from catalogue references')
  }
  const registry = {
    schemaVersion: 'sage.expert-registry.v1',
    designStatus: 'design_only',
    counts: { managers: 3, agents: 50, total: 53 },
    experts,
  }
  return { registry, avatarAssets, moduleSource: rendererModule(registry) }
}

export function assertExpertProjectionCurrent(assetsRoot = defaultAssetsRoot, projection = defaultProjection) {
  const result = loadExpertRendererAssets(assetsRoot)
  if (readFileSync(projection, 'utf8') !== result.moduleSource) {
    throw new Error('Expert renderer projection is stale; run node scripts/experts/renderer-assets.mjs --write')
  }
  return result
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const [mode, ...extra] = process.argv.slice(2)
  if (!['--write', '--check'].includes(mode) || extra.length > 0) {
    throw new Error('Usage: node scripts/experts/renderer-assets.mjs --write|--check')
  }
  if (mode === '--write') {
    const { moduleSource } = loadExpertRendererAssets()
    writeFileSync(defaultProjection, moduleSource)
  } else {
    assertExpertProjectionCurrent()
  }
  console.log(`Expert renderer ${mode.slice(2)}: 53 designs and 53 avatars (${relative(repoRoot, dirname(defaultProjection))})`)
}
