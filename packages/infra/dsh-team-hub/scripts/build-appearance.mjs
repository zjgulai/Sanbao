import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { loadThemeSources } from "../../../../scripts/lib/theme-source-loader.mjs";

const source = await loadThemeSources(fileURLToPath(new URL("../../../../", import.meta.url)));
const { settings, tokens, shared } = source;
const defaults = settings.DEFAULT_THEME_STUDIO_SETTINGS;
const allowed = {
  themeId: settings.THEME_IDS, uiFont: settings.UI_FONT_IDS, codeFont: settings.CODE_FONT_IDS,
  uiFontSize: settings.UI_FONT_SIZES, codeFontSize: settings.CODE_FONT_SIZES
};
const header = "/* @generated by scripts/build-appearance.mjs; DO NOT EDIT. Values: shared/client/sanbao-tokens.ts and dsh-theme-local typography. */\n";
const base = tokens.buildThemeTokenOverrides(defaults);
const typography = Object.fromEntries(Object.entries(base).filter(([key]) => key.includes("font")));
const declarations = overrides => Object.entries(overrides).map(([key, pair]) => `  ${key}: ${pair.light};`).join("\n");
let css = header + shared.SANBAO_TOKEN_CSS + `\n:root, body {\n${declarations(typography)}\n}\n`;
for (const { id, scheme } of source.identities) {
  css += `:root[data-sanbao-theme="${id}"] { color-scheme: ${scheme}; }\n`;
}
for (const field of settings.THEME_TYPOGRAPHY_FIELDS) {
  for (const value of allowed[field]) {
    const overrides = tokens.buildThemeTokenOverrides({ ...defaults, [field]: value });
    const changed = Object.fromEntries(Object.entries(overrides).filter(([key, pair]) => typography[key] && pair.light !== base[key].light));
    if (!Object.keys(changed).length) continue;
    css += `:root[data-${field.toLowerCase()}="${value}"], body[data-${field.toLowerCase()}="${value}"] {\n${declarations(changed)}\n}\n`;
  }
}
const properties = Object.entries(allowed).map(([field, values]) => ` * @property {${values.map(value => JSON.stringify(value)).join(" | ")}} ${field}`).join("\n");
const js = header + `/**
 * @typedef {Object} Appearance
${properties}
 */
/** @type {Record<string, readonly unknown[]>} */
const allowed = ${JSON.stringify(allowed, null, 2)};
export const DEFAULT_APPEARANCE = Object.freeze(${JSON.stringify(defaults)});
/** Validate the wire value and project only fixed identity/typography fields.
 * @param {unknown} value
 * @returns {Appearance | undefined}
 */
export function decodeAppearance(value) {
  if (!value || typeof value !== "object" || Array.isArray(value)) return undefined;
  const record = /** @type {Record<string, unknown>} */ (value);
  for (const [field, values] of Object.entries(allowed)) {
    if (!Object.hasOwn(record, field) || !values.includes(record[field])) return undefined;
  }
  return /** @type {Appearance} */ ({ ${Object.keys(allowed).map(field => `${field}: record.${field}`).join(", ")} });
}
`;
let stale = false;
for (const [name, content] of [["appearance.generated.css", css], ["appearance.generated.js", js]]) {
  const file = new URL(`../admin-ui/${name}`, import.meta.url);
  if (process.argv.includes("--check")) {
    let current;
    try { current = readFileSync(file, "utf8"); } catch { /* Missing artifact is stale. */ }
    if (current !== content) { console.error(`Stale generated appearance asset: ${name}`); stale = true; }
  } else writeFileSync(file, content);
}
if (stale) process.exitCode = 1;
else console.log(`Appearance assets ${process.argv.includes("--check") ? "checked" : "generated"}: 3 themes, 4 typography fields`);
