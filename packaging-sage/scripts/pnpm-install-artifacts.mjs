import {
  lstatSync,
  readdirSync,
  rmSync,
} from 'node:fs'
import { join } from 'node:path'

function lstatIfPresent(path) {
  try {
    return lstatSync(path)
  } catch (error) {
    if (error !== null && typeof error === 'object' && error.code === 'ENOENT') return undefined
    throw error
  }
}

function requireRealDirectory(path, label) {
  const entry = lstatIfPresent(path)
  if (entry === undefined) return false
  if (entry.isSymbolicLink() || !entry.isDirectory()) {
    throw new Error(`${label} must be a real directory: ${path}`)
  }
  return true
}

function appendPackageLocalBinFarms(packageNodeModules, generatedBinFarms) {
  const appendPackage = packageRoot => {
    const localNodeModules = join(packageRoot, 'node_modules')
    const localNodeModulesEntry = lstatIfPresent(localNodeModules)
    if (localNodeModulesEntry === undefined) return
    if (localNodeModulesEntry.isSymbolicLink() || !localNodeModulesEntry.isDirectory()) {
      throw new Error(`pnpm package-local node_modules must be a real directory: ${localNodeModules}`)
    }
    generatedBinFarms.push(join(localNodeModules, '.bin'))
  }

  for (const packageName of readdirSync(packageNodeModules)) {
    if (packageName === '.bin') continue
    const packagePath = join(packageNodeModules, packageName)
    const packageEntry = lstatIfPresent(packagePath)
    if (packageEntry === undefined || packageEntry.isSymbolicLink() || packageEntry.isFile()) continue
    if (!packageEntry.isDirectory()) {
      throw new Error(`pnpm package entry must be a file, symlink, or real directory: ${packagePath}`)
    }
    if (!packageName.startsWith('@')) {
      appendPackage(packagePath)
      continue
    }
    for (const scopedName of readdirSync(packagePath)) {
      const scopedPackagePath = join(packagePath, scopedName)
      const scopedEntry = lstatIfPresent(scopedPackagePath)
      if (scopedEntry === undefined || scopedEntry.isSymbolicLink() || scopedEntry.isFile()) continue
      if (!scopedEntry.isDirectory()) {
        throw new Error(`pnpm scoped package entry must be a file, symlink, or real directory: ${scopedPackagePath}`)
      }
      appendPackage(scopedPackagePath)
    }
  }
}

/**
 * Remove only paths generated by pnpm itself. In particular, do not recursively search retained
 * package contents for names such as `.bin`: a package may publish an internal node_modules tree,
 * and that published content belongs to the retained package by default.
 */
export function removeExactPnpmInstallerArtifacts(nodeModules) {
  if (!requireRealDirectory(nodeModules, 'installed node_modules')) {
    throw new Error(`installed node_modules is missing: ${nodeModules}`)
  }
  const virtualStore = join(nodeModules, '.pnpm')
  const hasVirtualStore = requireRealDirectory(virtualStore, 'pnpm virtual store')

  const exactFiles = [
    join(nodeModules, '.modules.yaml'),
    join(nodeModules, '.pnpm-workspace-state-v1.json'),
    join(nodeModules, '.pnpm', 'lock.yaml'),
  ]
  let removedFiles = 0
  for (const path of exactFiles) {
    const entry = lstatIfPresent(path)
    if (entry === undefined) continue
    if (entry.isSymbolicLink() || !entry.isFile()) {
      throw new Error(`pnpm installer metadata must be a regular file before removal: ${path}`)
    }
    rmSync(path)
    removedFiles += 1
  }

  const generatedBinFarms = [join(nodeModules, '.bin')]
  if (hasVirtualStore) {
    for (const entryName of readdirSync(virtualStore)) {
      const entryRoot = join(virtualStore, entryName)
      const entry = lstatIfPresent(entryRoot)
      if (entry === undefined || entry.isFile()) continue
      if (entry.isSymbolicLink() || !entry.isDirectory()) {
        throw new Error(`pnpm virtual store entry must be a regular file or real directory: ${entryRoot}`)
      }
      const packageNodeModules = entryName === 'node_modules'
        ? entryRoot
        : join(entryRoot, 'node_modules')
      const packageNodeModulesEntry = lstatIfPresent(packageNodeModules)
      if (packageNodeModulesEntry === undefined) continue
      if (packageNodeModulesEntry.isSymbolicLink() || !packageNodeModulesEntry.isDirectory()) {
        throw new Error(`pnpm package node_modules must be a real directory: ${packageNodeModules}`)
      }
      generatedBinFarms.push(join(packageNodeModules, '.bin'))
      appendPackageLocalBinFarms(packageNodeModules, generatedBinFarms)
    }
  }

  let removedBinFarms = 0
  for (const path of [...new Set(generatedBinFarms)].sort()) {
    const entry = lstatIfPresent(path)
    if (entry === undefined) continue
    if (entry.isSymbolicLink() || !entry.isDirectory()) {
      throw new Error(`pnpm generated .bin path must be a real directory before removal: ${path}`)
    }
    rmSync(path, { recursive: true, force: true })
    removedBinFarms += 1
  }

  process.stdout.write(`[sage-packaging] removed ${String(removedFiles)} exact pnpm metadata files and ${String(removedBinFarms)} generated .bin link farms\n`)
  return Object.freeze({ removedFiles, removedBinFarms })
}
